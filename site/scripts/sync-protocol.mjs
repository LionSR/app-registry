// Generates the pages that come from the protocol repo (the `protocol/` submodule),
// so the site never holds a hand-copied PROTOCOL.md or README text:
//   - one page per release tag, 1.0.0 and later:  src/content/docs/protocol/<version>.md
//   - README sections as guide pages:             src/content/docs/{guides,reference}/*.md
//   - README sections embedded in hand-written pages: src/generated/*.md
//   - README images:                               public/readme/*.png
// Runs from astro.config.mjs, so `astro dev` and `astro build` always see fresh output.
// All outputs are listed in site/.gitignore.

import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROTOCOL_REPO = join(SITE, '..', 'protocol');
const DOCS = join(SITE, 'src', 'content', 'docs');
const PARTIALS = join(SITE, 'src', 'generated');
const IMAGES = join(SITE, 'public', 'readme');
export const REPO_URL = 'https://github.com/LionSR/AgenticPublicationProtocol';

// README sections that become their own pages. Several sections on one page keep their headings.
const README_PAGES = [
	{ out: 'guides/install.md', title: 'Install and update', sections: ['Install and Update'] },
	{ out: 'guides/publish.md', title: 'Publish a paper', sections: ['Publish a paper'] },
	{ out: 'guides/read.md', title: 'Use a published paper', sections: ['Use a published paper'] },
	{ out: 'reference/skills.md', title: 'Skills', sections: ['Skills', 'External skills and extensions'] },
];

// README sections embedded in hand-written pages (see src/content/docs/about.mdx).
const README_PARTIALS = [
	{ out: 'motivation.md', section: 'Motivation' },
	{ out: 'what-is-app.md', section: 'What is APP', stopAt: 'This repository contains:' },
];

const git = (...args) => execFileSync('git', ['-C', PROTOCOL_REPO, ...args], { encoding: 'utf8' });
const NOTICE = (src) => `<!-- Generated by site/scripts/sync-protocol.mjs from ${src}. Do not edit. -->\n\n`;
const frontmatter = (fields) => `---\n${Object.entries(fields).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join('\n')}\n---\n\n`;

function write(path, content) {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, content);
}

/** Release versions from vX.Y.Z tags, newest first. Pre-1.0 drafts are not published. */
function protocolVersions() {
	const versions = git('tag', '--list', 'v*')
		.split('\n')
		.map((t) => t.trim().match(/^v(\d+)\.(\d+)\.(\d+)$/))
		.filter((m) => m && Number(m[1]) >= 1)
		.map((m) => m.slice(1, 4).map(Number))
		.sort((a, b) => b[0] - a[0] || b[1] - a[1] || b[2] - a[2])
		.map((v) => v.join('.'));
	if (!versions.length) throw new Error('No v1.0.0 or later tags found in protocol/');
	return versions;
}

/** "## Heading" sections of a Markdown file, by heading text. */
function sections(md) {
	const out = new Map();
	let current = null;
	for (const line of md.split('\n')) {
		const heading = line.match(/^## (.+)$/);
		if (heading) out.set((current = heading[1].trim()), []);
		else if (current) out.get(current).push(line);
	}
	return out;
}

/** Point README-relative links at the right place on the site or on GitHub. */
function rewriteLinks(md, withBase) {
	return md.replace(/(!?)\[([^\]]*)\]\(([^)\s]+)\)/g, (whole, bang, text, href) => {
		if (/^(https?:|mailto:|\/)/.test(href)) return whole;
		let to;
		if (href.startsWith('assets/readme/')) to = withBase(`/readme/${href.slice('assets/readme/'.length)}`);
		else if (href === 'PROTOCOL.md') to = withBase('/protocol/latest/');
		else if (href === '#publish-a-paper') to = withBase('/guides/publish/');
		else if (href === '#license') to = `${REPO_URL}#license`;
		else if (href.startsWith('#')) return whole;
		else to = `${REPO_URL}/blob/main/${href.replace(/^\.\//, '')}`;
		return `${bang}[${text}](${to})`;
	});
}

/** @param {(path: string) => string} withBase applies the site's base path to an internal link */
export function syncFromProtocolRepo(withBase = (p) => p) {
	for (const dir of ['protocol', 'guides', 'reference']) rmSync(join(DOCS, dir), { recursive: true, force: true });
	for (const dir of [PARTIALS, IMAGES]) rmSync(dir, { recursive: true, force: true });

	const versions = protocolVersions();
	const latest = versions[0];
	for (const v of versions) {
		const body = git('show', `v${v}:PROTOCOL.md`).replace(/^# .*\n+/, '');
		const released = git('log', '-1', '--format=%cs', `v${v}`).trim();
		const older = v === latest ? '' : `:::caution\nThis is an older version of the protocol. The current version is [${latest}](${withBase(`/protocol/${latest}/`)}).\n:::\n\n`;
		write(
			join(DOCS, `protocol/${v}.md`),
			// Explicit slug: the default slugger would drop the dots in "1.0.0".
			frontmatter({ slug: `protocol/${v}`, title: `Protocol ${v}`, description: `Agentic Publication Protocol, version ${v} (tag v${v}, ${released}).` }) +
				NOTICE(`PROTOCOL.md at tag v${v}`) +
				older +
				rewriteLinks(body, withBase),
		);
	}

	// README sections come from the commit the submodule is pinned to.
	const readme = sections(git('show', 'HEAD:README.md'));
	const section = (name, stopAt) => {
		const lines = readme.get(name);
		if (!lines) throw new Error(`README section "## ${name}" not found`);
		const text = lines.join('\n');
		return (stopAt && text.includes(stopAt) ? text.slice(0, text.indexOf(stopAt)) : text).trim();
	};

	for (const page of README_PAGES) {
		const body = page.sections
			// Demote ### to ## so Starlight's table of contents picks them up.
			.map((name) => (page.sections.length > 1 ? `## ${name}\n\n` : '') + section(name).replace(/^### /gm, '## '))
			.join('\n\n');
		write(join(DOCS, page.out), frontmatter({ title: page.title }) + NOTICE('README.md') + rewriteLinks(body, withBase) + '\n');
	}
	for (const part of README_PARTIALS) {
		write(join(PARTIALS, part.out), NOTICE('README.md') + rewriteLinks(section(part.section, part.stopAt), withBase) + '\n');
	}

	cpSync(join(PROTOCOL_REPO, 'assets', 'readme'), IMAGES, { recursive: true });
	return { versions, latest };
}
