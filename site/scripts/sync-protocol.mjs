// Generates the docs pages that come from the protocol repo, so the site never
// holds a hand-copied version of PROTOCOL.md or the README.
//   - one page per release tag:       src/content/docs/protocol/<version>.md
//   - README sections as guide pages:  src/content/docs/{guides/*,reference/*}.md
//   - README sections for the About page: src/generated/*.md
//   - README images:                   public/readme/*.png
// Runs from astro.config.mjs, so `astro dev` and `astro build` always see fresh output.

import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROTOCOL_REPO = join(SITE, '..', 'protocol');
const DOCS = join(SITE, 'src', 'content', 'docs');
export const REPO_URL = 'https://github.com/LionSR/AgenticPublicationProtocol';

// README section title -> generated page. Sections not listed stay README-only.
const README_PAGES = [
	{ out: 'guides/install.md', title: 'Install and update', sections: ['Install and Update'] },
	{ out: 'guides/publish.md', title: 'Publish a paper', sections: ['Publish a paper'] },
	{ out: 'guides/read.md', title: 'Use a published paper', sections: ['Use a published paper'] },
	{ out: 'reference/skills.md', title: 'Skills', sections: ['Skills', 'External skills and extensions'] },
];

// Output files this script owns; listed in site/.gitignore.
export const GENERATED = ['protocol', 'guides', 'reference'];

// README sections embedded in hand-written pages (src/generated/<file>).
const README_PARTIALS = [
	{ out: 'motivation.md', section: 'Motivation' },
	{ out: 'what-is-app.md', section: 'What is APP', stopAt: 'This repository contains:' },
];

const git = (...args) => execFileSync('git', ['-C', PROTOCOL_REPO, ...args], { encoding: 'utf8' });

function semverDesc(a, b) {
	const pa = a.split('.').map(Number);
	const pb = b.split('.').map(Number);
	for (let i = 0; i < 3; i++) if (pa[i] !== pb[i]) return pb[i] - pa[i];
	return 0;
}

function rewriteLinks(md) {
	return md.replace(/(!?)\[([^\]]*)\]\(([^)\s]+)\)/g, (whole, bang, text, href) => {
		if (/^(https?:|mailto:|\/)/.test(href)) return whole;
		let to;
		if (href.startsWith('assets/readme/')) to = '/readme/' + href.slice('assets/readme/'.length);
		else if (href === 'PROTOCOL.md') to = '/protocol/latest/';
		else if (href === '#publish-a-paper') to = '/guides/publish/';
		else if (href === '#license') to = `${REPO_URL}#license`;
		else if (href.startsWith('#')) return whole;
		else to = `${REPO_URL}/blob/main/${href.replace(/^\.\//, '')}`;
		return `${bang}[${text}](${to})`;
	});
}

function frontmatter(fields) {
	const lines = Object.entries(fields).map(([k, v]) => `${k}: ${JSON.stringify(v)}`);
	return `---\n${lines.join('\n')}\n---\n\n`;
}

const NOTICE = (src) => `<!-- Generated by site/scripts/sync-protocol.mjs from ${src}. Do not edit. -->\n\n`;

function splitSections(md) {
	const sections = new Map();
	let current = null;
	for (const line of md.split('\n')) {
		const m = line.match(/^## (.+)$/);
		if (m) {
			current = m[1].trim();
			sections.set(current, []);
		} else if (current) sections.get(current).push(line);
	}
	return sections;
}

function write(rel, content) {
	const path = join(DOCS, rel);
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, content);
}

export function syncFromProtocolRepo() {
	for (const g of GENERATED) rmSync(join(DOCS, g), { recursive: true, force: true });

	// Protocol: one page per vX.Y.Z tag.
	const versions = git('tag', '--list', 'v*')
		.split('\n')
		.map((t) => t.trim())
		.filter((t) => /^v\d+\.\d+\.\d+$/.test(t))
		.map((t) => t.slice(1))
		.sort(semverDesc);
	if (versions.length === 0) throw new Error('No vX.Y.Z tags found in protocol');
	const latest = versions[0];

	for (const v of versions) {
		const body = git('show', `v${v}:PROTOCOL.md`).replace(/^# .*\n+/, '');
		const released = git('log', '-1', '--format=%cs', `v${v}`).trim();
		const aside =
			v === latest
				? ''
				: `:::caution\nThis is an older version of the protocol. The current version is [${latest}](/protocol/${latest}/).\n:::\n\n`;
		write(
			`protocol/${v}.md`,
			frontmatter({
				// Explicit slug: the default slugger would drop the dots in "1.0.0".
				slug: `protocol/${v}`,
				title: `Protocol ${v}`,
				description: `Agentic Publication Protocol, version ${v} (tag v${v}, ${released}).`,
			}) +
				NOTICE(`PROTOCOL.md at tag v${v}`) +
				aside +
				rewriteLinks(body),
		);
	}

	// README sections, from the checked-out submodule commit.
	const readme = splitSections(git('show', 'HEAD:README.md'));
	for (const page of README_PAGES) {
		const parts = page.sections.map((name) => {
			const lines = readme.get(name);
			if (!lines) throw new Error(`README section "## ${name}" not found`);
			let text = lines.join('\n');
			if (page.stopAt && text.includes(page.stopAt)) text = text.slice(0, text.indexOf(page.stopAt));
			// Demote ### to ## so Starlight's table of contents picks them up.
			text = text.replace(/^### /gm, '## ');
			return page.sections.length > 1 ? `## ${name}\n${text}` : text;
		});
		write(page.out, frontmatter({ title: page.title }) + NOTICE('README.md') + rewriteLinks(parts.join('\n').trim()) + '\n');
	}

	const partials = join(SITE, 'src', 'generated');
	rmSync(partials, { recursive: true, force: true });
	mkdirSync(partials, { recursive: true });
	for (const part of README_PARTIALS) {
		const lines = readme.get(part.section);
		if (!lines) throw new Error(`README section "## ${part.section}" not found`);
		let text = lines.join('\n');
		if (part.stopAt && text.includes(part.stopAt)) text = text.slice(0, text.indexOf(part.stopAt));
		writeFileSync(join(partials, part.out), NOTICE('README.md') + rewriteLinks(text.trim()) + '\n');
	}

	const imgOut = join(SITE, 'public', 'readme');
	rmSync(imgOut, { recursive: true, force: true });
	cpSync(join(PROTOCOL_REPO, 'assets', 'readme'), imgOut, { recursive: true });

	return { versions, latest };
}
